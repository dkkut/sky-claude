#!/bin/sh
# ============================================================
#  Периодическая перезагрузка конфигурации.
#
#  Сертификат продлевает отдельный контейнер certbot в общем томе.
#  Чтобы nginx подхватил новые файлы, ему нужен reload. Отдельный
#  контейнер не может послать сигнал в этот, поэтому перезагружаемся
#  сами раз в 6 часов.
#
#  Скрипт запускается штатным entrypoint-ом образа nginx — важно
#  не подменять command контейнера, иначе entrypoint не отработает
#  и шаблоны из /etc/nginx/templates не будут развёрнуты.
# ============================================================
set -e

(
  while :; do
    sleep 6h
    # Пока nginx не поднялся, reload вернёт ошибку — она не должна
    # ронять цикл.
    nginx -s reload 2>/dev/null || true
  done
) &

exit 0
