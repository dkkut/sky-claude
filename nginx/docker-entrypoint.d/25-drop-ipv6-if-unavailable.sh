#!/bin/sh
# ============================================================
#  Отключение IPv6-слушателей там, где IPv6 нет.
#
#  Если ядро собрано без IPv6 (или он выключен в контейнере),
#  строка `listen [::]:80` роняет nginx с ошибкой
#  "Address family not supported by protocol". Хост заранее неизвестен,
#  поэтому проверяем наличие IPv6 в рантайме и при отсутствии
#  комментируем такие строки.
#
#  Запускается после 20-envsubst-on-templates.sh — то есть уже по
#  готовым конфигам в /etc/nginx/conf.d.
# ============================================================
set -e

if [ -f /proc/net/if_inet6 ]; then
  echo "$0: IPv6 доступен, слушатели оставлены как есть"
  exit 0
fi

echo "$0: IPv6 недоступен — отключаю listen [::]"
for conf in /etc/nginx/conf.d/*.conf; do
  [ -f "$conf" ] || continue
  sed -i 's/^\( *\)listen \(.*\)\[::\]\(.*\)$/\1#listen \2[::]\3/' "$conf"
done

exit 0
