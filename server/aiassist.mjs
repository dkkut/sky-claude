export const VOICE_STYLE = [
  'Это голосовой разговор: твой ответ будет прочитан вслух.',
  'Отвечай короткими живыми фразами, без таблиц, markdown и длинных списков, код не зачитывай.',
  'Если вопрос непонятен или не хватает данных — задай один короткий уточняющий вопрос.',
].join(' ');

const money = (n) => `${Number(n).toLocaleString('ru-RU')} ₽`;

/** Сводка по аккаунту — строкой для системной части запроса. */
export const accountBrief = async (profileId) => {
  const parts = [];
  try {
    const w = await wallet.getState(profileId, 0);
    parts.push(`Баланс кошелька: ${money(w.balance)}; Prime Points: ${w.points}.`);
  } catch { /* кошелёк недоступен — справку без него */ }

  try {
    const { rows } = await query(
      `SELECT status, count(*)::int AS n FROM market_orders
        WHERE buyer_id = $1 GROUP BY status`, [profileId]);
    if (rows.length) {
      parts.push(`Заказы человека как покупателя по статусам: ${rows.map((r) => `${r.status} — ${r.n}`).join(', ')}.`);
    } else parts.push('Заказов как покупатель у человека нет.');

    const last = await query(
      `SELECT title_snap, status, total_kop, created_at FROM market_orders
        WHERE buyer_id = $1 ORDER BY created_at DESC LIMIT 5`, [profileId]);
    if (last.rows.length) {
      parts.push('Последние заказы: ' + last.rows.map((r) =>
        `«${String(r.title_snap).slice(0, 60)}» — ${r.status}, ${money(Number(r.total_kop) / 100)}, ${r.created_at.toISOString().slice(0, 10)}`).join('; ') + '.');
    }
  } catch { /* нет таблицы — пропускаем */ }

  try {
    const { rows } = await query(
      'SELECT count(*)::int AS n FROM market_notifications WHERE user_id = $1 AND read_at IS NULL', [profileId]);
    parts.push(`Непрочитанных уведомлений Market: ${rows[0]?.n ?? 0}.`);
  } catch { /* пропускаем */ }

  if (!parts.length) return '';
  return [
    'Справка об аккаунте собеседника (только для чтения, данные точные, других у тебя нет):',
    ...parts,
    'Отвечай по этой справке, когда спрашивают про баланс, заказы, уведомления. Если нужных данных в справке нет — скажи, что не видишь их, и подскажи, в каком разделе Sky это посмотреть. Ты ничего не можешь делать за человека: ни платить, ни отменять, ни менять.',
  ].join('\n');
};
