-- ============================================================
--  «Просмотр один раз» и «самоуничтожение» — на сервере.
--
--  Обе пометки жили только в браузере: сервер хранил сообщение вечно, а
--  прятал его клиент получателя. То есть обещание было ложным —
--  достаточно было перезагрузить страницу или открыть другой клиент.
--
--  Оговорка, которую честно держать в голове: сервер может перестать
--  отдавать сообщение, но не может отобрать то, что уже показано.
--  Снимок экрана и изменённый клиент, сохранивший полученный текст,
--  этим не останавливаются — так устроено везде, включая Telegram.
-- ============================================================

-- Когда сообщение должно исчезнуть. NULL — не исчезает.
ALTER TABLE messages ADD COLUMN IF NOT EXISTS destroy_at TIMESTAMPTZ;

-- Показывается один раз: после открытия получателем текст стирается.
ALTER TABLE messages ADD COLUMN IF NOT EXISTS once BOOLEAN NOT NULL DEFAULT FALSE;

-- Уборщик ходит по сроку, поэтому индекс только по тем, у кого он есть.
CREATE INDEX IF NOT EXISTS messages_destroy_idx
  ON messages (destroy_at) WHERE destroy_at IS NOT NULL AND NOT deleted;
