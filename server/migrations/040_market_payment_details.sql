-- ============================================================
--  Sky Market: реквизиты продавца
-- ============================================================
--
-- Sky не хранит деньги сделки — покупатель переводит продавцу напрямую.
-- Значит, покупателю нужно знать, КУДА переводить, и узнать это он
-- должен от сервера, а не из переписки: реквизиты, присланные в чат,
-- подменяются тем, кто в чат попал.
--
-- Поэтому реквизиты живут в профиле продавца и выдаются сервером
-- покупателю его собственного заказа — и никому больше.
--
-- Лежат зашифрованными. Это платёжные данные живого человека: в дампе
-- базы, в журналах и в выдаче каталога им не место.

ALTER TABLE market_sellers
  ADD COLUMN IF NOT EXISTS payment_details_enc TEXT;

-- Отметка о том, что реквизиты заданы. Нужна, чтобы отвечать на вопрос
-- «может ли этот продавец получить деньги» одним взглядом на строку,
-- без расшифровки: расшифровка ради проверки на пустоту — это лишний
-- повод достать ключ.
ALTER TABLE market_sellers
  ADD COLUMN IF NOT EXISTS has_payment_details BOOLEAN NOT NULL DEFAULT FALSE;
