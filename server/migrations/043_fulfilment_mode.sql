-- ============================================================
--  Sky Market: режим работы магазина
-- ============================================================
--
-- Продавец работает одним из двух способов, и выбирает он сам:
--
--   direct    — напрямую. Заказ собрали и отправили покупателю: службой
--               или своими силами, как и было.
--
--   warehouse — через свой склад. Продавец собирает заказы в одну
--               поставку, отправляет её на свой склад, а уже со склада
--               везёт покупателю своими силами — с тем же подтверждением
--               получения от покупателя.
--
-- Почему это колонка продавца, а не выбор при каждой отправке: способ
-- работы у магазина один, и именно от него зависит, какие шаги заказа
-- вообще существуют. Выбор «на каждый заказ» означал бы, что половина
-- заказов уехала мимо склада, а остатки на складе врут.

ALTER TABLE market_sellers
  ADD COLUMN IF NOT EXISTS fulfilment_mode TEXT NOT NULL DEFAULT 'direct'
  CHECK (fulfilment_mode IN ('direct', 'warehouse'));

-- Какой именно склад. Проверяется на принадлежность продавцу при
-- сохранении: чужой склад своим режимом работы не назначишь.
ALTER TABLE market_sellers
  ADD COLUMN IF NOT EXISTS fulfilment_warehouse_id TEXT
  REFERENCES logi_warehouses(id) ON DELETE SET NULL;

-- ============================================================
--  Заказ внутри поставки
-- ============================================================

-- В какой поставке едет этот заказ на склад. Пусто — заказ пока никуда
-- не положен либо продавец работает напрямую.
ALTER TABLE market_orders
  ADD COLUMN IF NOT EXISTS supply_id TEXT REFERENCES logi_supplies(id) ON DELETE SET NULL;

-- Когда заказ доехал до склада. Ставится сервером, когда до склада
-- доезжает вся поставка: отдельной отметки «этот доехал, а этот нет» у
-- одной коробки быть не может.
ALTER TABLE market_orders
  ADD COLUMN IF NOT EXISTS at_warehouse_at TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS market_orders_supply_idx
  ON market_orders (supply_id) WHERE supply_id IS NOT NULL;
