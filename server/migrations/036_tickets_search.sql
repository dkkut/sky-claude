-- Поиск по афише не должен зависеть от локали базы.
--
-- Раньше каталог искал так:  lower(e.title) LIKE lower('%запрос%').
-- Функция lower() в PostgreSQL приводит регистр по правилам LC_CTYPE
-- той базы, в которой она выполняется. На одной сборке libc «Концерт»
-- превращается в «концерт», на другой остаётся как есть — и тогда
-- поиск по-русски молча становится чувствительным к регистру: человек
-- ищет «концерт», а находит только тех, кто написал название с
-- маленькой буквы.
--
-- Проверено на двух базах: на musl (образ alpine) складывание работало,
-- на glibc с локалью C — нет. Полагаться на то, какая libc окажется на
-- сервере, нельзя.
--
-- Поэтому строку для поиска готовит сервер на JavaScript, где
-- toLowerCase() работает по Unicode одинаково везде, и кладёт её в
-- отдельную колонку. База в приведении регистра больше не участвует —
-- она только сравнивает уже приведённое.

ALTER TABLE ticket_events
  ADD COLUMN IF NOT EXISTS search_text TEXT NOT NULL DEFAULT '';

-- Разовое заполнение для уже существующих строк. На базе, где lower()
-- складывает кириллицу, оно точное; где не складывает — строка станет
-- точной при первом сохранении мероприятия. Новых строк это не
-- касается: их готовит сервер.
UPDATE ticket_events e
   SET search_text = lower(
         coalesce(e.title, '') || ' ' || coalesce(e.venue, '') || ' '
         || coalesce(e.city, '') || ' ' || coalesce(e.category, '') || ' '
         || coalesce((SELECT coalesce(o.display_name, p.name)
                        FROM profiles p
                        LEFT JOIN ticket_organizers o ON o.profile_id = p.id
                       WHERE p.id = e.organizer_id), ''))
 WHERE e.search_text = '';
