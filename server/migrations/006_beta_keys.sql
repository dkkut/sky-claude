-- ============================================================
--  Ключи закрытого бета-теста.
--
--  Пока приложение не готово, посторонним внутри делать нечего.
--  Ключей всего несколько, и это временная мера: когда бета
--  закончится, достаточно очистить таблицу (или BETA_KEYS в .env) —
--  проверка сама перестанет срабатывать.
--
--  Хранится не сам ключ, а его HMAC: дамп базы не выдаёт ключи,
--  которыми можно войти.
-- ============================================================

CREATE TABLE IF NOT EXISTS beta_keys (
  key_hash     TEXT PRIMARY KEY,

  -- Чей это ключ — «мой», «команда». Нужно только чтобы понимать,
  -- какой из них отзывать.
  label        TEXT        NOT NULL DEFAULT '',

  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_used_at TIMESTAMPTZ,
  uses         BIGINT      NOT NULL DEFAULT 0 CHECK (uses >= 0)
);
