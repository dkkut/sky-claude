-- ============================================================
--  Непрочитанное, которое переживает перезагрузку.
--
--  Отметки о прочтении лежали в message_reads и использовались только
--  для галочек у отправителя. Своё собственное «прочитано» сервер
--  клиенту не сообщал: при подключении все входящие приходили со
--  статусом «доставлено», и счётчик непрочитанного возвращался после
--  каждой перезагрузки страницы.
--
--  Плюс отдельная пометка «оставить непрочитанным» — та самая
--  «пометить как новое». Это свойство участника чата, а не сообщения:
--  человек помечает непрочитанной всю переписку.
-- ============================================================

ALTER TABLE chat_members ADD COLUMN IF NOT EXISTS marked_unread BOOLEAN NOT NULL DEFAULT FALSE;

-- Чтение своих отметок — самый частый запрос в снимке при подключении.
CREATE INDEX IF NOT EXISTS message_reads_user_idx ON message_reads (user_id, message_id);
