-- ============================================================
--  Sky Market: логотип товара
-- ============================================================
--
-- У товара есть фотографии — это снимки самой вещи. Логотип это другое:
-- квадратная марка, по которой товар узнают в списке. У игрового лота
-- она особенно нужна: скриншот предмета в мелкой карточке не читается,
-- а эмблема игры или продавца читается.
--
-- Поэтому логотип — отдельная картинка, а не первая из галереи. Файл
-- лежит там же, где остальные картинки маркета, и по тем же правилам:
-- имя файла выводится из идентификатора товара, тип определяется по
-- первым байтам.

ALTER TABLE market_products
  ADD COLUMN IF NOT EXISTS has_logo BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE market_products
  ADD COLUMN IF NOT EXISTS logo_mime TEXT;
