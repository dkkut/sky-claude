-- Как показывать текст песни: решает тот, кто загрузил трек.
--   auto   — как раньше: есть метки [мм:сс] — по строкам, нет — просто текст;
--   static — всегда целиком, метки времени (если есть) не используются;
--   synced — по строкам (нужны метки времени; без них показывается целиком).
ALTER TABLE music_tracks ADD COLUMN IF NOT EXISTS lyrics_mode TEXT NOT NULL DEFAULT 'auto';
