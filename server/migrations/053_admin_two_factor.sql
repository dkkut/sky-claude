-- ============================================================
--  Второй фактор для администраторов — обязателен
-- ============================================================
--
-- Панель защищена ролями, повторным подтверждением личности и вторым
-- ключом владельца. Всё это стоит на одном допущении: в панель вошёл
-- тот, кто должен. А вход был по одному фактору — коду на почту. Кто
-- добрался до почты администратора, получал панель целиком.
--
-- Дальше по цепочке ничего не спасает. Повторное подтверждение личности
-- присылает код на ту же почту. То есть вся конструкция держалась на
-- ящике, за который мы не отвечаем.
--
-- Поэтому второй фактор становится условием работы, а не настройкой по
-- желанию. Без него у администратора нет ни одного права: не «панель
-- закрыта», а именно ни одного права — модули спрашивают то же самое.
--
-- Срок, а не рубильник
-- ────────────────────
-- Выложить это одним днём значило бы утром отобрать работу у всех, кто
-- вчера работал, — включая тех, кто разбирает жалобы и отвечает людям.
-- Поэтому у каждого администратора есть свой срок:
--
--   кто был администратором до этой правки — две недели;
--   кому права выдают теперь — срок наступает сразу: человек получает
--   их в ту же минуту, когда может включить второй фактор, и ждать
--   тут нечего.
--
-- Запертым насмерть не оказывается никто: включение второго фактора
-- живёт в настройках Sky ID, а не в панели, и правами не закрыто. То
-- есть выход из запрета всегда открыт тому, кто вошёл в свою учётную
-- запись, — и только ему.

ALTER TABLE profiles ADD COLUMN IF NOT EXISTS admin_2fa_due TIMESTAMPTZ;

-- Тем, кто уже работает, — две недели от выкладки.
UPDATE profiles
   SET admin_2fa_due = now() + interval '14 days'
 WHERE is_admin AND admin_2fa_due IS NULL;

COMMENT ON COLUMN profiles.admin_2fa_due IS
  'С этого момента права администратора действуют только при включённом втором факторе';
