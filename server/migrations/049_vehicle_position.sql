-- ============================================================
--  Положение машины
-- ============================================================
--
-- Карта логистики до сих пор показывала транспорт там, где его не было:
-- точка выводилась из хэша идентификатора, а «движение» было ровным
-- скольжением между двумя такими же выдуманными точками. Выглядело живо
-- и означало ровно ничего.
--
-- Взять настоящее положение было неоткуда: у машины в базе не было
-- координат вовсе. Теперь есть — и вместе с ними время, когда их
-- передали. Время здесь не для порядка: положение, переданное вчера,
-- это не «машина стоит там», а «где она сейчас, неизвестно». Карта на
-- то и смотрит, и старую точку не показывает.
--
-- Пусто — машины на карте нет. Это честнее выдуманной точки: по ней
-- диспетчер отправил бы заказ не туда.

ALTER TABLE logi_tc_vehicles
  ADD COLUMN IF NOT EXISTS lat DOUBLE PRECISION;
ALTER TABLE logi_tc_vehicles
  ADD COLUMN IF NOT EXISTS lng DOUBLE PRECISION;
ALTER TABLE logi_tc_vehicles
  ADD COLUMN IF NOT EXISTS position_at TIMESTAMPTZ;
