-- ============================================================
--  Sky Market: транспортная компания как перевозчик маркета
-- ============================================================
--
-- Продавцу нужно найти компанию, которая отвезёт товар покупателю, и
-- заплатить ей напрямую. Sky в этих деньгах не участвует так же, как не
-- участвует в деньгах самой сделки: чужих денег мы не держим.
--
-- Поэтому здесь две вещи.
--
-- Первая — реквизиты компании. Хранятся зашифрованными и выдаются
-- продавцу того заказа, который эта компания везёт: платить ей будет
-- он. Присланные в переписке реквизиты подменяет тот, кто в переписку
-- попал, — значит, приходить они должны от сервера.
--
-- Вторая — связь с перевозчиками маркета. Отдельного реестра «те же
-- компании, но для маркета» заводить нельзя: два списка одних и тех же
-- перевозчиков однажды разойдутся, и продавец выберет из одного, а
-- везти будет некому. Вместо этого у строки перевозчика появляется
-- ссылка на компанию, и создаётся эта строка сама, когда компанию
-- заводят.

ALTER TABLE logi_tc
  ADD COLUMN IF NOT EXISTS payment_details_enc TEXT;

ALTER TABLE logi_tc
  ADD COLUMN IF NOT EXISTS has_payment_details BOOLEAN NOT NULL DEFAULT FALSE;

-- Какая компания стоит за этим перевозчиком маркета. Пусто у внешних
-- служб — у CDEK и Почты компании в Sky нет.
ALTER TABLE market_carriers
  ADD COLUMN IF NOT EXISTS company_id TEXT REFERENCES logi_tc(id) ON DELETE CASCADE;

CREATE UNIQUE INDEX IF NOT EXISTS market_carriers_company_idx
  ON market_carriers (company_id) WHERE company_id IS NOT NULL;
