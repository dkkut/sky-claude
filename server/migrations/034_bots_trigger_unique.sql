-- Триггер inline занимается сразу, а не в момент публикации.
--
-- В 033 уникальность стояла только среди опубликованных ботов. Из-за
-- этого черновик спокойно брал себе «#погода», уже занятую живым
-- ботом, — и узнавал об этом только тогда, когда модератор нажимал
-- «Опубликовать». Публикация в этот момент падала на ограничении
-- базы, то есть ошибкой сервера в ответ на правильное действие.
--
-- Теперь триггер уникален среди всех, у кого включён inline. Занять
-- его нельзя с самого начала, отказ приходит сразу и владельцу бота,
-- а не модератору через неделю.

DROP INDEX IF EXISTS bots_inline_trigger_key;

-- ── Сначала развести тех, кто успел занять один триггер ──────────
--
--  Прежнее правило это позволяло, значит такие строки в базе есть, и
--  индекс на них просто не создастся. Миграция, падающая на
--  собственных данных, — это не миграция.
--
--  Право на триггер остаётся за опубликованным, а среди равных — за
--  тем, кто занял его раньше. У остальных inline выключается: бот
--  остаётся как был, просто перестаёт откликаться на «#…», пока
--  владелец не выберет другое слово.
WITH ranked AS (
  SELECT id,
         row_number() OVER (
           PARTITION BY lower(inline_trigger)
           ORDER BY (status = 'published') DESC, created_at, id
         ) AS rn
    FROM bots
   WHERE inline_enabled AND inline_trigger IS NOT NULL
)
UPDATE bots SET inline_enabled = FALSE
 WHERE id IN (SELECT id FROM ranked WHERE rn > 1);

CREATE UNIQUE INDEX IF NOT EXISTS bots_inline_trigger_key
  ON bots (lower(inline_trigger))
  WHERE inline_enabled AND inline_trigger IS NOT NULL;
