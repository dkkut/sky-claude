-- ============================================================
--  Google Карты: разобранные адреса
-- ============================================================
--
-- Один и тот же адрес спрашивают десятки раз: при каждом открытии карты
-- заказа, при каждом обновлении списка. Каждый такой вопрос — это и
-- деньги, и ещё один повод отправить чужой адрес третьей стороне.
-- Поэтому ответ запоминается.
--
-- Ненайденный адрес запоминается тоже, и это не оплошность: без такой
-- записи опечатка в адресе спрашивалась бы у Google снова и снова,
-- каждый раз впустую.
--
-- Адрес здесь лежит открытым текстом, и это сознательно. Он и так ушёл
-- наружу к Google — шифровать его здесь означало бы делать вид, будто
-- он остался при нас. Зато рядом нет ни заказа, ни того, кто спрашивал:
-- по этой таблице нельзя узнать, кто куда возит.

CREATE TABLE IF NOT EXISTS maps_geocode (
  address    TEXT PRIMARY KEY,
  lat        DOUBLE PRECISION,
  lng        DOUBLE PRECISION,
  found      BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS maps_geocode_age_idx ON maps_geocode (created_at);
