-- ============================================================
--  Блокировка учётной записи целиком
-- ============================================================
--
-- Бан до сих пор был привязан к профилю. У человека их двое, и
-- забаненный переходил на второй: наказание означало «неудобство», а не
-- «вы здесь больше не работаете». Администратор при этом был уверен в
-- обратном.
--
-- Поэтому блокировка появляется на уровне Sky ID и живёт рядом с баном
-- профиля, а не вместо него. Это два разных решения:
--
--   бан профиля — «эта витрина закрыта», второй профиль работает;
--   блокировка   — «этот человек здесь больше не работает», закрыты все
--   учётной        профили, включая те, что он заведёт после.
--   записи
--
-- Второе тяжелее первого и потому требует большего: права модерации,
-- подтверждения личности и записи в журнал. Владельца не блокирует
-- никто — по той же причине, по которой его нельзя разжаловать.
--
-- Срок хранится тем же способом, что у бана профиля: время, до которого
-- закрыто, а не признак. Признак пришлось бы снимать вручную, и снятые
-- блокировки копились бы годами.

ALTER TABLE sky_ids
  ADD COLUMN IF NOT EXISTS blocked_until TIMESTAMPTZ;

ALTER TABLE sky_ids
  ADD COLUMN IF NOT EXISTS blocked_reason TEXT NOT NULL DEFAULT '';

ALTER TABLE sky_ids
  ADD COLUMN IF NOT EXISTS blocked_by TEXT REFERENCES profiles(id) ON DELETE SET NULL;

ALTER TABLE sky_ids
  ADD COLUMN IF NOT EXISTS blocked_at TIMESTAMPTZ;

-- Спрашивается на каждом изменяющем запросе: пусть спрашивается быстро.
CREATE INDEX IF NOT EXISTS sky_ids_blocked_idx
  ON sky_ids (blocked_until) WHERE blocked_until IS NOT NULL;
