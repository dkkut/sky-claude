/**
 * Пропуск на личную загрузку внутри совместного просмотра.
 *
 * Зачем отдельный файл. Кино решает, кому что видно, в film.mjs, а
 * «Вместе» — в together.mjs, и together.mjs уже спрашивает кино о
 * правах. Если бы теперь и кино стало спрашивать «Вместе», два модуля
 * начали бы вызывать друг друга по кругу. Поэтому единственный вопрос,
 * который им обоим нужен, вынесен сюда: здесь нет ни одного импорта,
 * кроме базы, и спрашивать отсюда можно откуда угодно.
 *
 * Что этот пропуск даёт и чего не даёт.
 *
 * Даёт ровно одно: прочитать запись о фильме и получить его поток,
 * пока идёт сеанс, в который человека позвали. Это и есть «показать
 * своё кино тому, кого я позвал».
 *
 * Не даёт ничего больше. Фильм не появляется ни в каталоге, ни в
 * поиске, ни в «продолжить просмотр», ни в чьих-либо закладках: все
 * эти выборки отбирают по «опубликовано или своё», и личная загрузка
 * не подходит ни под то, ни под другое. Править, удалять, публиковать
 * и менять постер по-прежнему может только владелец — эти действия
 * сверяют владельца напрямую и сюда не заглядывают вовсе.
 *
 * Три условия, и все обязательны.
 *
 * 1. Сеанс идёт. Не «запланирован» и не «завершён»: пока не начали —
 *    показывать нечего, после конца — уже нечего. Доступ гаснет в тот
 *    же миг, когда владелец нажимает «Завершить».
 *
 * 2. Человек внутри. Позванный, но не вошедший, ещё ничего не видит;
 *    вышедший и убранный — уже ничего.
 *
 * 3. Фильм принадлежит владельцу сеанса. Своим делятся, чужим — нет.
 *    Без этого условия получилась бы цепочка: мне показали, а я
 *    показал дальше. Оно же страхует на будущее — даже если когда-то
 *    появится способ завести сеанс на чужой записи, пропуск по нему
 *    не выпишется.
 */
import { query } from './db.mjs';

/**
 * Открыта ли этому человеку личная загрузка — потому что его позвали.
 *
 * Отвечает только про личное (status = 'private'). Отклонённое
 * проверкой сюда не попадает намеренно: у него состояние 'rejected', и
 * если бы им можно было делиться, совместный просмотр стал бы способом
 * раздавать то, что модерация не пропустила.
 */
export const sharedInSession = async (movieId, viewerId) => {
  if (!movieId || !viewerId) return false;
  const { rows } = await query(
    `SELECT 1
       FROM together_sessions s
       JOIN together_participants p
         ON p.session_id = s.id AND p.user_id = $2 AND p.status = 'joined'
       JOIN film_movies m
         ON m.id = s.content_id AND m.owner_id = s.owner_id
      WHERE s.content_kind = 'movie'
        AND s.content_id = $1
        AND s.status = 'live'
        AND m.status = 'private'
      LIMIT 1`,
    [String(movieId), String(viewerId)],
  );
  return rows.length > 0;
};
