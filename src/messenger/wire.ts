/**
 * Тонкая прослойка между стором мессенджера и сокетом.
 *
 * Стор должен уметь отправлять (отложенное сообщение, наступил срок), а
 * сокет — менять стор при входящих. Прямая пара импортов замкнула бы
 * модули друг на друга; здесь же нет ни одного импорта, поэтому цикла
 * не возникает: сокет кладёт сюда свою функцию отправки, стор её зовёт.
 */
export interface Outgoing { type: string; payload?: unknown }

let sink: ((msg: Outgoing) => void) | null = null;

/** Вызывает socket.ts при загрузке модуля. */
export const setWireSink = (fn: ((msg: Outgoing) => void) | null) => { sink = fn; };

/** Отправка «в сеть». Пока сокета нет — сообщение просто теряется. */
export const wireSend = (msg: Outgoing) => { sink?.(msg); };
