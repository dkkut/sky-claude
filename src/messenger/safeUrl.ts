/**
 * Ссылка на вложение, пригодная для показа.
 *
 * Адрес вложения выводит сервер из идентификатора загруженного файла:
 * он всегда наш и всегда одного вида — /api/files/f-<uuid>. Ничего
 * другого в src и href попадать не должно.
 *
 * Раньше ссылку присылал клиент, а клиент может быть переписан: строка
 * вида javascript:… выполняется как код, а ссылка на чужой сервер
 * сообщает ему адрес каждого, кто открыл переписку. Сервер такие уже
 * отбрасывает (server/chats.mjs), но проверка повторяется на месте
 * показа: одной проверки на пути данных мало.
 */
const OUR_FILE = /^\/api\/files\/f-[0-9a-f-]{36}$/;

export const safeMediaUrl = (raw?: string): string | undefined => {
  const value = typeof raw === 'string' ? raw.trim() : '';
  if (!value) return undefined;
  // Свежая отправка: файл ещё загружается, показываем его из памяти
  // самой вкладки. Такая ссылка никуда наружу не ведёт.
  if (value.startsWith('blob:')) return value;
  return OUR_FILE.test(value) ? value : undefined;
};
