/**
 * Подгрузка частей приложения, переживающая обновление.
 *
 * Приложение разрезано на куски, и каждый подгружается тогда, когда
 * человек открывает соответствующий экран. В имени куска есть отпечаток
 * его содержимого — так браузеру можно разрешить держать его у себя
 * вечно. Из-за этого же при каждом обновлении имена меняются.
 *
 * Отсюда беда, которая случается ровно в одном случае, зато со всеми.
 * Человек открыл приложение, оставил его в фоне, мы выложили новую
 * версию — старые куски с диска исчезли. Он возвращается, нажимает
 * вкладку, страница просит кусок по старому имени и получает честные
 * «нет такого». Браузер говорит «Importing a module script failed», и
 * человек упирается в экран ошибки.
 *
 * Кнопка «Попробовать снова» тут бессильна, и это не оплошность кнопки:
 * React запоминает неудачную загрузку и на повторный заход отдаёт ту же
 * неудачу, не обращаясь к сети вовсе. Сколько ни нажимай — тот же
 * несуществующий адрес.
 *
 * Единственное, что помогает, — перечитать страницу: тогда придёт свежий
 * список кусков с новыми именами. Это и делается здесь, один раз и
 * молча. Человеку незачем знать, что мы в этот момент обновились, — ему
 * нужно, чтобы открылась вкладка, которую он нажал.
 *
 * Почему один раз. Если после перезагрузки кусок всё равно не пришёл,
 * дело не в обновлении: нет связи, лежит раздача, сломана сборка. Тогда
 * повторять бессмысленно — это уже не лечение, а бесконечный круг
 * перезагрузок. В этом случае ошибку показываем честно.
 */
import { lazy, type ComponentType } from 'react';

/** Метка о том, что мы уже перезагружались из-за пропавшего куска. */
const MARK = 'sky:chunk-reload';
/** Столько времени считаем недавнюю перезагрузку своей. */
const RECENT_MS = 30_000;

/**
 * Похоже ли это на пропавший кусок.
 *
 * Единого текста у браузеров нет: Safari говорит «Importing a module
 * script failed», Chrome — «Failed to fetch dynamically imported
 * module», Firefox — про загрузку модуля. Поэтому смотрим на несколько
 * примет разом, а не на одну строку.
 */
export const isChunkError = (error: unknown): boolean => {
  const text = `${(error as Error)?.name ?? ''} ${(error as Error)?.message ?? ''}`.toLowerCase();
  return /importing a module script|dynamically imported module|error loading dynamically|failed to fetch|module script failed|chunkloaderror|load failed|unexpected token '<'|expected expression, got '<'/.test(text);
};

const recentlyReloaded = (): boolean => {
  try {
    const at = Number(sessionStorage.getItem(MARK) ?? 0);
    return at > 0 && Date.now() - at < RECENT_MS;
  } catch {
    /* Приватный режим и запрещённое хранилище. Считаем, что не
       перезагружались: одна лишняя перезагрузка лучше тупика. */
    return false;
  }
};

const markReload = () => {
  try { sessionStorage.setItem(MARK, String(Date.now())); } catch { /* см. выше */ }
};

/** Убрать метку: страница ожила, и следующая пропажа снова достойна перезагрузки. */
export const clearChunkReloadMark = () => {
  try { sessionStorage.removeItem(MARK); } catch { /* см. выше */ }
};

/**
 * То же, что React.lazy, но переживающее обновление приложения.
 *
 * Порядок попыток: обычная загрузка; при неудаче — ещё одна через
 * четверть секунды (короткий обрыв связи лечится именно этим); и только
 * потом перезагрузка страницы.
 *
 * Почему перезагружаемся на ЛЮБОЙ неудаче, а не только на той, что
 * похожа на пропавший кусок. Потому что текст ошибки зависит от того,
 * как раздача отвечает на несуществующий файл. Правильно настроенная
 * отвечает «нет такого», и браузер говорит про модуль. Но раздача,
 * которая на любой неизвестный адрес отдаёт index.html — а так устроен
 * едва ли не каждый одностраничный сайт, — вернёт на запрос куска
 * страницу HTML, и браузер попробует прочитать её как код. Получится
 * ошибка разбора, ни словом не упоминающая модули. Причина при этом
 * одна и та же, и лечение одно и то же.
 *
 * От бесконечного круга спасает не разбор текста, а метка: перезагрузка
 * бывает одна. Если и после неё не вышло — значит дело не в обновлении,
 * и ошибку надо показать честно.
 */
export const lazyChunk = <T extends ComponentType<any>>(
  load: () => Promise<{ default: T }>,
) => lazy<T>(async () => {
  try {
    return await load();
  } catch {
    /* Вторая попытка. Куски отдаются обычными запросами, и им мешает
       всё то же, что мешает любому запросу: метро, лифт, потерянная
       на секунду сеть. */
    try {
      await new Promise((r) => { setTimeout(r, 250); });
      return await load();
    } catch (second) {
      if (recentlyReloaded()) throw second;

      markReload();
      window.location.reload();

      /* Пока браузер перечитывает страницу, показывать нечего и падать
         незачем: обещание, которое никогда не исполнится, оставляет на
         экране заглушку загрузки до самой перезагрузки. */
      return new Promise<{ default: T }>(() => {});
    }
  }
});
