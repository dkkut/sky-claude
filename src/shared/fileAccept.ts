/**
 * Что предлагать в окне выбора файла.
 *
 * Казалось бы, «audio/*» — это и есть «любой звук», и писать больше
 * нечего. На деле окно выбора файлов не смотрит внутрь файла: оно
 * сопоставляет расширение с таблицей типов операционной системы. Если
 * в этой таблице для .m4a, .flac или .opus ничего не записано — а это
 * обычное дело, — файл становится серым и его нельзя выбрать. Человек
 * видит папку с записью подкаста, в которой «нет ни одного звукового
 * файла».
 *
 * Поэтому расширения перечисляются рядом с типом: браузер пускает
 * файл, если подошло хоть одно из условий. В Sky Music так было
 * сделано с самого начала, и там эта беда не воспроизводилась.
 *
 * Список намеренно совпадает с тем, что принимает сервер (он узнаёт
 * тип по первым байтам, а не по имени). Предлагать выбрать то, что
 * потом будет отвергнуто, — значит врать в окне выбора.
 */

/** Звук: mp3, m4a/aac, ogg/opus, wav, flac, webm. */
export const ACCEPT_AUDIO = [
  'audio/*',
  '.mp3', '.m4a', '.m4b', '.aac', '.mp4',
  '.ogg', '.oga', '.opus',
  '.wav', '.wave',
  '.flac',
  '.webm',
].join(',');

/** Видео: mp4, webm/mkv, mov, ogv, avi. */
export const ACCEPT_VIDEO = [
  'video/*',
  '.mp4', '.m4v',
  '.webm', '.mkv',
  '.mov', '.qt',
  '.ogv',
  '.avi',
].join(',');

/** Картинки: jpeg, png, webp. Ровно то, что опознаёт сервер. */
export const ACCEPT_IMAGE = [
  'image/*',
  '.jpg', '.jpeg', '.png', '.webp',
].join(',');

/**
 * Субтитры. Здесь перечисление обязательно вдвойне: у .srt
 * зарегистрированного типа нет вовсе, и по одному MIME такой файл не
 * выбрать нигде.
 */
export const ACCEPT_SUBTITLES = [
  '.vtt', '.srt',
  'text/vtt', 'text/plain',
].join(',');
