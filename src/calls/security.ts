/** Отпечаток ключа из описания соединения. */
const fingerprintOf = (sdp?: string | null): string => {
  if (!sdp) return '';
  const found = sdp.match(/^a=fingerprint:sha-256\s+([0-9A-Fa-f:]+)/im);
  return found ? found[1].toUpperCase().replace(/:/g, '') : '';
};

export interface CallSecurity {
  /** Четыре картинки — их сверяют на глаз. */
  emoji: string[];
  /** То же самое числами: удобнее продиктовать по телефону. */
  digits: string;
  /** Шифр, которым браузер защищает сам разговор. */
  cipher?: string;
}

/**
 * Считает код звонка. Возвращает null, пока стороны не обменялись
 * ключами: до этого сверять нечего.
 *
 * Отпечатки сортируются, поэтому обе стороны получают одинаковый
 * порядок и одинаковый код. Идентификатор звонка подмешивается, чтобы
 * код был свой у каждого разговора, а не один и тот же для этой пары
 * навсегда.
 */
export const computeCallSecurity = async (
  pc: RTCPeerConnection,
  callId: string,
): Promise<CallSecurity | null> => {
  const mine = fingerprintOf(pc.localDescription?.sdp);
  const theirs = fingerprintOf(pc.remoteDescription?.sdp);
  if (!mine || !theirs) return null;

  const material = [mine, theirs].sort().join('|') + '|' + callId;
  const bytes = new Uint8Array(
    await crypto.subtle.digest('SHA-256', new TextEncoder().encode(material)),
  );

  const emoji = [0, 1, 2, 3].map(i => EMOJI[bytes[i] % EMOJI.length]);
  // Четыре группы по три цифры: так их проще произносить и сверять.
  const digits = [0, 1, 2, 3]
    .map(i => String(((bytes[4 + i * 2] << 8) | bytes[5 + i * 2]) % 1000).padStart(3, '0'))
    .join(' ');

  return { emoji, digits, cipher: await srtpCipherOf(pc) };
};

/**
 * Каким шифром браузер защищает сам разговор.
 *
 * Значение не участвует в сверке — оно для тех, кому важно увидеть, что
 * шифрование не «на словах». Отсутствие имени шифра ничего плохого не
 * значит: браузеры называют его по-разному и не всегда сообщают.
 */
const srtpCipherOf = async (pc: RTCPeerConnection): Promise<string | undefined> => {
  try {
    const stats = await pc.getStats();
    let cipher: string | undefined;
    stats.forEach((report: any) => {
      if (report.type === 'transport' && report.dtlsState === 'connected') {
        cipher = report.srtpCipher || report.dtlsCipher || cipher;
      }
    });
    return cipher;
  } catch {
    return undefined;
  }
};
