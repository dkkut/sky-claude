/**
 * Код звонка: как убедиться, что между вами никого нет.
 *
 * Сам разговор WebRTC шифрует всегда — незашифрованного режима у него
 * не бывает, и звук с видео идут напрямую между устройствами, минуя
 * наш сервер. Проверять тут нечего: либо соединение установилось (и
 * оно зашифровано), либо не установилось вовсе.
 *
 * Слабое место в другом. Договориться о ключах стороны могут только
 * через сервер — он передаёт приглашение и ответ. Значит недобросовестный
 * сервер мог бы подменить ключи обеих сторон на свои и слушать разговор,
 * оставаясь посередине. Ни один шифр от этого сам по себе не спасает.
 *
 * Спасает сверка. Каждая сторона считает короткий код из отпечатков
 * ОБОИХ ключей — своего и собеседника. Если сервер подменил ключи, у
 * сторон окажутся разные отпечатки, а значит и разные коды. Достаточно
 * назвать код вслух: совпал — посередине никого нет.
 *
 * Это тот же приём, что в Telegram (четыре картинки), Signal и WhatsApp
 * (числа). Ничего своего здесь не изобретено: код — это обычный SHA-256
 * от отпечатков, посчитанный встроенным в браузер средством.
 */

