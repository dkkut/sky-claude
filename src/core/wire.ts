/**
 * Тонкая прослойка между теми, кто хочет что-то отправить в хаб, и самим
 * сокетом.
 *
 * Стор мессенджера должен уметь отправлять (наступил срок отложенного
 * сообщения), сигналинг звонков — тоже, а сокет при этом меняет их
 * состояние при входящих. Прямые импорты замкнули бы модули друг на
 * друга; здесь же нет ни одного импорта, поэтому цикла не возникает:
 * сокет кладёт сюда свою функцию отправки, остальные её зовут.
 */
export interface Outgoing { type: string; payload?: unknown }

let sink: ((msg: Outgoing) => void) | null = null;

/** Вызывает socket.ts при загрузке модуля. */
export const setWireSink = (fn: ((msg: Outgoing) => void) | null) => { sink = fn; };

/** Отправка «в сеть». Пока сокета нет — сообщение просто теряется. */
export const wireSend = (msg: Outgoing) => { sink?.(msg); };
