#!/usr/bin/env bash
# ============================================================
#  Настройка Sky AI — одной командой.
#
#      cd /opt/sky && bash scripts/set-ai-key.sh
#
#  Спрашивает три вещи: ключ модели, какую модель брать и нужна ли
#  расшифровка голосовых. Всё с проверкой: неверный ключ виден сразу,
#  а не тогда, когда человек напишет в чат и получит отказ.
#
#  Ключи на экране не появляются и в репозиторий не попадают: они живут
#  только в .env на этом сервере, права 600. Разговор с моделью идёт с
#  сервера, в браузер уходит готовый ответ — ключ клиенту не отдаётся
#  никогда.
#
#  Без ключа Sky AI честно пишет, что не настроен, и ничего не
#  выдумывает. Остальное приложение работает полностью.
# ============================================================
set -euo pipefail

cd "$(dirname "$0")/.."
[ -f .env ] || { echo "Здесь нет .env — запускайте из каталога приложения."; exit 1; }

# Читаем ввод с терминала: так работает и при запуске через «bash -s»,
# когда стандартный ввод занят самим скриптом.
if { : </dev/tty; } 2>/dev/null; then INPUT=/dev/tty; else INPUT=/dev/stdin; fi

ask() { read -r "$1" <"$INPUT"; }
ask_secret() { read -rs "$1" <"$INPUT"; echo; }

set_env() {
  local key="$1" val="$2"
  if grep -q "^$key=" .env; then
    # Значение подставляем через awk, а не sed: в ключе бывают символы,
    # которые sed принял бы за часть выражения замены.
    awk -v k="$key" -v v="$val" \
      'BEGIN{FS=OFS="="} $1==k {print k "=" v; done=1; next} {print} END{if(!done) print k "=" v}' \
      .env > .env.tmp && mv .env.tmp .env
  else
    printf '%s=%s\n' "$key" "$val" >> .env
  fi
  chmod 600 .env
}

echo "============================================"
echo " Sky AI — настройка"
echo "============================================"
echo
echo "Обычный чат Sky AI бесплатен для всех, кому вы открыли вход."
echo "Prime добавляет пересказ, разбор документов и картинок,"
echo "расшифровку записей."
echo

# ── 1. Ключ модели ─────────────────────────────────────────
echo "--- Шаг 1 из 3: ключ языковой модели ---"
echo
echo "Взять здесь: platform.openai.com -> API keys."
echo "Не забудьте пополнить счёт в разделе Billing, иначе ключ создастся,"
echo "но запросы будут отбиваться."
echo
echo "Если это не сам OpenAI, а совместимый прокси на своём адресе —"
echo "введите его ниже. Учтите: весь трафик Sky AI (переписка, файлы,"
echo "картинки пользователей) тогда идёт через владельца этого адреса,"
echo "а не только через OpenAI."
echo
printf 'Адрес поставщика [https://api.openai.com]: '
ask AI_URL
AI_URL="${AI_URL:-https://api.openai.com}"
# Код сам добавляет /v1/... к этому адресу — если ввели адрес уже
# с /v1 на конце (обычная запись для OpenAI-совместимых прокси),
# срезаем его здесь, иначе выйдет двойной /v1/v1/....
AI_URL="${AI_URL%/}"
AI_URL="${AI_URL%/v1}"
echo
printf 'Вставьте ключ и нажмите Enter. На экране он не появится.\n\n'
printf 'Ключ: '
ask_secret KEY
[ -n "$KEY" ] || { echo "Ключ пустой — ничего не меняю."; exit 1; }
echo "Принял ключ длиной ${#KEY} символов."
echo

# ── 2. Модель ──────────────────────────────────────────────
#  Выбор цифрой, а не вводом идентификатора: опечатка в названии
#  модели — самая частая причина «настроил, а не работает». Точные
#  цены здесь не печатаем: они меняются, а устаревшая цифра хуже,
#  чем её отсутствие. Актуальные — на openai.com/api/pricing.
echo "--- Шаг 2 из 3: какая модель ---"
echo
echo "  1) gpt-4o       — самая умная, дороже"
echo "  2) gpt-4o-mini  — заметно дешевле (по умолчанию)"
echo "  3) своё название — если знаете, что вводите"
echo
echo "Бесплатный чат ограничен 60 сообщениями в сутки на человека, так что"
echo "счёт растёт предсказуемо. Поменять модель можно этим же скриптом."
echo
printf 'Выбор [2]: '
ask CHOICE
case "${CHOICE:-2}" in
  1)    MODEL='gpt-4o' ;;
  2|'') MODEL='gpt-4o-mini' ;;
  3)    printf 'Название модели: '; ask MODEL ;;
  *)    MODEL="$CHOICE" ;;   # своё название — если знаете, что вводите
esac
echo "Модель: $MODEL"
echo

# ── Проба ──────────────────────────────────────────────────
#  Короткий запрос: он стоит копейки и сразу отвечает, принят ли ключ.
echo "Проверяю ключ пробным обращением ..."
BODY="$(printf '{"model":"%s","max_output_tokens":16,"input":"ответь словом: готово"}' "$MODEL")"
HTTP="$(curl -sS -o /tmp/ai-answer.$$ -w '%{http_code}' \
        -X POST "$AI_URL/v1/responses" \
        -H 'content-type: application/json' \
        -H "authorization: Bearer $KEY" \
        --data "$BODY" --max-time 30)" || true
HTTP="${HTTP:-000}"
ANSWER="$(head -c 300 /tmp/ai-answer.$$ 2>/dev/null || true)"
rm -f /tmp/ai-answer.$$

case "$HTTP" in
  2*) echo "Ключ принят (ответ $HTTP)." ;;
  000)
    echo "Не удалось достучаться до поставщика — похоже, нет связи."
    echo "Настройку не меняю."; exit 1 ;;
  401|403)
    echo "Ключ не принят (ответ $HTTP): $ANSWER"
    echo "Проверьте, что он скопирован целиком. Настройку не меняю."; exit 1 ;;
  404)
    echo "Такой модели нет, либо адрес не отвечает на /v1/responses (ответ $HTTP): $ANSWER"
    if [ "$AI_URL" != "https://api.openai.com" ]; then
      echo "Это не сам OpenAI — свои прокси часто понимают только старую"
      echo "ручку /v1/chat/completions и не знают /v1/responses. Уточните"
      echo "у владельца адреса, какую ручку он поддерживает."
    else
      echo "Проверьте название модели."
    fi
    echo "Настройку не меняю."; exit 1 ;;
  *)
    echo "Поставщик ответил $HTTP: $ANSWER"
    echo "Настройку не меняю."; exit 1 ;;
esac
echo

# ── 3. Расшифровка речи ────────────────────────────────────
#  Отдельный поставщик: языковая модель речь не расшифровывает. Шаг
#  необязательный — без него работает всё остальное.
echo "--- Шаг 3 из 3: расшифровка голосовых (необязательно) ---"
echo
echo "Языковая модель речь не расшифровывает — для этого нужен отдельный"
echo "поставщик. Подходит любой с ручкой /v1/audio/transcriptions:"
echo
echo "  · OpenAI Whisper — тот же ключ и адрес, что вы уже ввели в Шаге 1,"
echo "    подойдёт и здесь: адрес https://api.openai.com;"
echo "  · свой на сервере (faster-whisper-server, whisper.cpp) —"
echo "    тогда записи вообще не покидают машину. Для голосовых в"
echo "    переписке это важнее, чем кажется: люди не ждут, что их"
echo "    голосовое уедет к постороннему."
echo
echo "Пропустите, если не нужно: Sky AI честно напишет, что расшифровка"
echo "не подключена, и не станет ничего выдумывать."
echo
printf 'Настроить расшифровку сейчас? [д/Н]: '
ask WANT_STT
STT_KEY=''
STT_URL=''
case "$WANT_STT" in
  д|да|y|yes|Д|ДА|Y|YES)
    printf 'Адрес поставщика [https://api.openai.com]: '
    ask STT_URL
    STT_URL="${STT_URL:-https://api.openai.com}"
    STT_URL="${STT_URL%/}"

    printf 'Ключ (на экране не появится): '
    ask_secret STT_KEY
    [ -n "$STT_KEY" ] || { echo "Ключ пустой — расшифровку пропускаю."; STT_URL=''; }

    if [ -n "$STT_KEY" ]; then
      echo "Проверяю ..."
      # Спрашиваем список моделей: это самый дешёвый способ понять,
      # принят ли ключ. Не у всех своих серверов эта ручка есть,
      # поэтому 404 считаем не отказом, а «проверить не вышло».
      SHTTP="$(curl -sS -o /dev/null -w '%{http_code}' \
               -H "authorization: Bearer $STT_KEY" \
               "$STT_URL/v1/models" --max-time 20)" || true
      SHTTP="${SHTTP:-000}"
      case "$SHTTP" in
        2*)      echo "Ключ расшифровки принят." ;;
        401|403) echo "Ключ расшифровки не принят (ответ $SHTTP). Настройку не меняю."; exit 1 ;;
        000)     echo "До $STT_URL не достучаться. Настройку не меняю."; exit 1 ;;
        *)       echo "Проверить не вышло (ответ $SHTTP) — сохраню как есть." ;;
      esac
    fi
    ;;
  *) echo "Пропускаю: расшифровка останется выключенной." ;;
esac
echo

# ── Сохранение ─────────────────────────────────────────────
printf 'Сохранить настройки? [д/н]: '
ask YES
case "$YES" in
  д|да|y|yes|Д|ДА|Y|YES) ;;
  *) echo "Не сохраняю."; exit 0 ;;
esac

set_env AI_API_KEY  "$KEY"
set_env AI_MODEL    "$MODEL"
set_env AI_BASE_URL "$AI_URL"
unset KEY

if [ -n "$STT_KEY" ]; then
  set_env STT_API_KEY  "$STT_KEY"
  set_env STT_BASE_URL "$STT_URL"
  set_env STT_MODEL    "whisper-1"
  unset STT_KEY
fi

echo
echo "==> Перезапускаю приложение"
# Настройки уже сохранены. Если перезапуск не удался, сказать об этом
# важнее, чем оборвать скрипт: человеку останется выполнить одну
# команду, а не гадать, записался ли ключ.
if docker compose up -d api; then
  sleep 6
else
  echo
  echo "Перезапустить не вышло. Настройки сохранены — выполните вручную:"
  echo "    docker compose up -d api"
fi

echo
echo "============================================"
echo " Готово"
echo "============================================"
echo "  Чат Sky AI        — работает у всех, подписка не нужна"
echo "  Пересказ, файлы,"
echo "  картинки          — работают у тех, у кого Sky Prime"
echo "  Адрес поставщика  — $AI_URL"
if [ -n "$STT_URL" ]; then
  echo "  Расшифровка       — включена ($STT_URL)"
else
  echo "  Расшифровка       — не настроена (запустите скрипт ещё раз)"
fi
echo
echo "  Пересказ выпусков подкастов тоже работает от этого ключа."
echo
echo "Ключи лежат только в .env на этом сервере, права 600."
