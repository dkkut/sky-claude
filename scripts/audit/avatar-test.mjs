import { call, mkuser } from './lib.mjs';
const S = process.argv[2];
let pass = 0, fail = 0; const ok = (c, m, x = '') => { if (c) { pass++; console.log('ok  ', m); } else { fail++; console.log('FAIL', m, x); } };
const U = await mkuser(S, 'avt'), V = await mkuser(S, 'avv');
const mk = (kb) => 'data:image/png;base64,' + 'A'.repeat(Math.floor(kb * 1024 * 4 / 3 / 4) * 4);
const patch = (u, body, pid = u.pid) => call(`/api/skyid/profiles/${pid}`, { method: 'PATCH', body: JSON.stringify(body) }, u.tok);
const get = async (u) => (await call('/api/skyid/profiles', {}, u.tok)).data.profiles.find((p) => p.id === u.pid);
let r = await patch(U, { avatar: mk(50) });
ok(r.status === 200 && r.data.profile.avatar?.length > 1000, 'малый аватар (50 КБ) сохраняется', r.text.slice(0, 120));
ok((await get(U)).avatar?.length > 1000, 'после перечитывания профиля аватар на месте');
r = await patch(U, { avatar: mk(400) });
ok(r.status === 400 && r.data.error === 'invalid_avatar', 'слишком большой аватар (400 КБ) → 400 invalid_avatar, а не молчаливое стирание', `${r.status} ${r.text.slice(0, 120)}`);
ok((await get(U)).avatar?.length > 1000, 'после отказа прежний аватар не стёрт');
r = await patch(U, { avatar: 'javascript:alert(1)' });
ok(r.status === 400, 'мусорное значение → 400', String(r.status));
r = await patch(U, { avatar: '' });
ok(r.status === 200 && !r.data.profile.avatar, 'пустая строка явно убирает аватар');
r = await patch(V, { avatar: mk(10) }, U.pid);
ok(r.status === 404 || r.status === 403, 'чужой профиль менять нельзя', String(r.status));
ok(!(await get(U)).avatar, 'чужой запрос аватар жертвы не изменил');
console.log(`\n${pass} ok, ${fail} fail`);
