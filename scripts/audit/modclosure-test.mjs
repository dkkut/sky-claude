// Закрытие модулей из админки (server/modclosure.mjs).  (. env.sh; node scripts/audit/modclosure-test.mjs <каталог>)
import { execSync } from 'node:child_process';
import { call, mkuser } from './lib.mjs';
const S = process.argv[2];
const q = (s) => execSync(`psql postgres://sky:sky@127.0.0.1/sky -tA -c "${s.replace(/["$]/g, '\\$&')}"`).toString().trim();
let ok = 0, bad = 0; const t = (n, c, x = '') => { if (c) { ok++; console.log('ok  ', n); } else { bad++; console.log('FAIL', n, x); } };
q(`update profiles set username='old'||substr(md5(random()::text),1,6) where lower(username)='ownertest'`);
const own = await mkuser(S, 'modown'); q(`update profiles set username='ownertest' where id='${own.pid}'`);
const usr = await mkuser(S, 'modusr');
q('delete from closed_modules');
const put = (k, b, u) => call(`/api/admin/modules/${k}`, { method: 'PUT', body: JSON.stringify(b) }, u.tok);
const status = async () => (await call('/api/platform/status')).data.closedModules;
t('по умолчанию ничего не закрыто', Object.keys(await status()).length === 0);
t('человек не может закрыть модуль', (await put('music', { closed: true, reason: 'тест' }, usr)).status === 403);
t('человек не видит список', (await call('/api/admin/modules', {}, usr.tok)).status === 403);
let r = await call('/api/admin/modules', {}, own.tok);
t('владелец видит список модулей', r.status === 200 && r.data.modules.some((m) => m.key === 'music') && r.data.modules.some((m) => m.key === 'cloud'));
t('без причины закрыть нельзя', (await put('music', { closed: true }, own)).data.error === 'reason_required');
t('неизвестный модуль отклоняется', (await put('nope', { closed: true, reason: 'тест' }, own)).status === 404);
t('закрытие с причиной', (await put('music', { closed: true, reason: 'Обновляем каталог' }, own)).status === 200);
let st = await status();
t('публично виден закрытый модуль, причина скрыта', 'music' in st && st.music.reason === undefined);
await put('go', { closed: true, reason: 'Сбой у поставщика', showReason: true }, own);
st = await status();
t('причина показывается, если разрешено', st.go?.reason === 'Сбой у поставщика');
t('закрытие попало в журнал', Number(q(`select count(*) from admin_log where type='module_closed'`)) >= 2);
await put('music', { closed: false }, own); await put('go', { closed: false }, own);
t('после открытия список пуст', Object.keys(await status()).length === 0);
console.log(`\nИтого: ${ok} ok, ${bad} fail`); process.exit(bad ? 1 : 0);
