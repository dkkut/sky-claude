// Детский аккаунт (модуль напрямую): DATABASE_URL=postgres://sky:sky@127.0.0.1:5432/skytest REDIS_URL=redis://127.0.0.1:6379 JWT_SECRET=... ENCRYPTION_KEY=... node scripts/audit/childaccount-test.mjs
import { query, pool } from '../../server/db.mjs';
import * as ch from '../../server/childaccount.mjs';
let ok = 0, bad = 0;
const t = (n, c) => { if (c) ok++; else { bad++; console.log('FAIL', n); } };
const sky = `sky-ct-${Date.now()}`;
await query(`INSERT INTO sky_ids (id, email) VALUES ($1, $2)`, [sky, sky + '@t.test']);
const mk = async (n) => { const id = `acc-ct-${n}-${Date.now()}`; await query(`INSERT INTO profiles (id, sky_id, username, name) VALUES ($1,$2,$3,$4)`, [id, sky, `ct${n}${Date.now()}`.slice(0, 20), `N${n}`]); return id; };
const parent = await mk(1), kid = await mk(2);
t('bad pin', (await ch.createChild(sky, parent, { existingId: kid, pin: '12' })).error === 'bad_pin');
t('self', (await ch.createChild(sky, parent, { existingId: parent, pin: '1234' })).error === 'self_child');
t('foreign', (await ch.createChild('other', parent, { existingId: kid, pin: '1234' })).error === 'not_found');
t('create', (await ch.createChild(sky, parent, { existingId: kid, pin: '1234', birthYear: new Date().getFullYear() - 8 })).ok);
t('dup', (await ch.createChild(sky, parent, { existingId: kid, pin: '1234' })).error === 'already_child');
t('parent not child', await ch.isGuardianSession(parent));
t('kid is child', !(await ch.isGuardianSession(kid)));
t('market closed', (await ch.childBlockedFor(kid, '/api/market/products', 'GET')) === 'market');
t('money closed', (await ch.childBlockedFor(kid, '/api/wallet', 'GET')) === 'money');
t('balance ok', (await ch.childBlockedFor(kid, '/api/wallet/balance', 'GET')) === null);
t('skyid write closed', (await ch.childBlockedFor(kid, '/api/skyid/profiles', 'POST')) === 'skyid');
t('select open', (await ch.childBlockedFor(kid, '/api/skyid/profiles/acc-x/select', 'POST')) === null);
t('music open', (await ch.childBlockedFor(kid, '/api/music/tracks', 'GET')) === null);
t('parent free', (await ch.childBlockedFor(parent, '/api/market/products', 'GET')) === null);
await ch.updateChild(sky, kid, { money: true, modules: ['ai'] });
await new Promise((r) => setTimeout(r, 4100));
t('money allowed', (await ch.childBlockedFor(kid, '/api/wallet', 'GET')) === null);
t('market now open', (await ch.childBlockedFor(kid, '/api/market/products', 'GET')) === null);
t('ai closed', (await ch.childBlockedFor(kid, '/api/ai/send', 'POST')) === 'ai');
t('wrong pin', (await ch.checkGuardianPin(sky, kid, '0000')).error === 'bad_pin_code');
t('right pin', (await ch.checkGuardianPin(sky, kid, '1234')).ok);
for (let i = 0; i < 5; i++) await ch.checkGuardianPin(sky, kid, '9999');
t('locked', (await ch.checkGuardianPin(sky, kid, '1234')).error === 'pin_locked');
t('remove foreign', (await ch.removeChild('other', kid)).error === 'not_found');
t('remove', (await ch.removeChild(sky, kid)).ok);
await query('DELETE FROM profiles WHERE sky_id = $1', [sky]); await query('DELETE FROM sky_ids WHERE id = $1', [sky]).catch(() => {});
console.log(`childaccount: ${ok} ok, ${bad} fail`); await pool.end(); process.exit(bad ? 1 : 0);
