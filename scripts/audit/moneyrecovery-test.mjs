// Фраза восстановления SkyMoney и 13-е слово (модуль напрямую). Запуск: DATABASE_URL=… REDIS_URL=… JWT_SECRET=… node scripts/audit/moneyrecovery-test.mjs
import { createRequire } from 'node:module';
process.chdir(new URL('../../server/', import.meta.url).pathname);
const m = await import('../../server/moneyrecovery.mjs');
const { query } = await import('../../server/db.mjs');
let ok = 0, bad = 0; const t = (n, c) => { c ? ok++ : bad++; console.log(`${c ? 'ok  ' : 'FAIL'} ${n}`); };
const id = `mr-test-${Date.now()}`;
const created = await m.createPhrase(id);
t('фраза: 12 слов', created.words.length === 12 && created.words.every((w) => /^[a-z]+$/.test(w)));
const dump = JSON.stringify((await query('SELECT * FROM money_recovery WHERE sky_id=$1', [id])).rows[0]);
t('в базе нет слов фразы', created.words.every((w) => !dump.includes(w)));
t('без 13-го слова фраза открывает настоящий режим', (await m.checkPhrase(id, created.words.join(' '))).mode === 'real');
t('регистр и лишние пробелы не важны', (await m.checkPhrase(id, '  ' + created.words.join('  ').toUpperCase())).mode === 'real');
t('13-е слово слишком короткое отклонено', (await m.setExtra(id, 'abc')).error === 'bad_extra');
t('13-е слово задано', (await m.setExtra(id, 'моё слово 13')).hasExtra === true);
t('фраза без 13-го слова — пустой кошелёк', (await m.checkPhrase(id, created.words)).mode === 'decoy');
t('фраза и верное 13-е слово — настоящие данные', (await m.checkPhrase(id, created.words, 'моё слово 13')).mode === 'real');
t('неверное 13-е слово — отказ', (await m.checkPhrase(id, created.words, 'другое слово')).error === 'invalid_phrase');
t('11 слов — отказ', (await m.checkPhrase(id, created.words.slice(1))).ok === false);
let r; for (let i = 0; i < 6; i++) r = await m.checkPhrase(id, 'able acid acorn actor adapt agile alarm album alert alley amber ankle');
t('после 5 неверных — пауза', r.error === 'too_many_attempts');
t('во время паузы верная фраза не принимается', (await m.checkPhrase(id, created.words, 'моё слово 13')).error === 'too_many_attempts');
await query(`UPDATE money_recovery SET locked_until=NULL WHERE sky_id=$1`, [id]);
t('после паузы верная фраза снова работает', (await m.checkPhrase(id, created.words, 'моё слово 13')).mode === 'real');
const again = await m.createPhrase(id);
t('новая фраза сбрасывает 13-е слово', (await m.recoveryInfo(id)).hasExtra === false && again.words.join() !== created.words.join());
t('старая фраза после замены не подходит', (await m.checkPhrase(id, created.words)).ok === false);
t('ответ-пустышка: состояние — нули', JSON.stringify(m.decoyReply('GET', '/api/wallet').body) === '{"balance":0,"points":0,"transactions":[]}');
t('ответ-пустышка: баланс — нули', m.decoyReply('GET', '/api/wallet/balance').body.balance === 0);
t('ответ-пустышка: операции недоступны', m.decoyReply('POST', '/api/wallet/exchange').status === 503);
await query('DELETE FROM money_recovery WHERE sky_id=$1', [id]);
console.log(`\n${ok} ok, ${bad} fail`); process.exit(bad ? 1 : 0);
