#!/bin/bash
# ============================================================
#  Хук PAM: срабатывает на каждый успешный вход по SSH (session open).
#
#  НЕ деплоится автоматически из CI (сознательно нет в списке файлов
#  в .github/workflows/deploy.yml) — это скрипт, который выполняется
#  от root при каждом входе по SSH, и автоматическое обновление такого
#  файла при обычном git push стало бы отдельной дырой: кто угодно,
#  кто может запушить в ветку деплоя, получил бы код с правами root на
#  машине. Обновляется только руками, по этой же инструкции — см.
#  DEPLOY.md, раздел «Аварийное выключение при подозрении на взлом».
#
#  Подключение (делается один раз, вручную, от root):
#    install -o root -g root -m 755 scripts/ssh-login-hook.sh /opt/sky/ssh-login-hook.sh
#    echo 'session optional pam_exec.so /opt/sky/ssh-login-hook.sh' \
#      >> /etc/pam.d/sshd
#
#  Считает вход подозрительным, пока владелец не подтвердит по ссылке
#  из письма за 10 минут — иначе сервер выключается тем же сторожем,
#  что и при взломе администраторского аккаунта (server/breach.mjs,
#  scripts/breach-watch.sh + scripts/sky-breach-watch.service).
#
#  Правка (версия 2026-10-02): раньше КАЖДЫЙ вход безусловно
#  перезаписывал общий файл токена и заводил ещё один независимый
#  10-минутный таймер — если за эти 10 минут случался ещё один вход
#  (например, та же сессия отладки с несколькими переподключениями),
#  ссылка из более раннего письма переставала совпадать с файлом
#  токена: её клик молча проваливался («ссылка недействительна»), а
#  более ранний таймер всё равно срабатывал и выключал машину — даже
#  если более позднее подключение уже было благополучно подтверждено.
#  Проверка «уже идёт окно подтверждения» закрыла это для
#  последовательных входов.
#
#  Правка (версия 2026-10-03): та проверка сама была гонкой — она
#  читает файл и только потом (отдельной командой) решает его
#  перезаписать, а между этими двумя шагами ничего не мешает второму
#  процессу hook'а вклиниться. Если два входа по SSH происходят
#  практически одновременно (например, VS Code Remote-SSH или
#  мобильный SSH-клиент открывают сразу несколько параллельных
#  сессий), оба запуска хука могут одновременно увидеть «активного
#  токена ещё нет» и оба пройти проверку — и тогда второй вызов
#  перезаписывает токен первого уже после того, как письмо с первым
#  (теперь недействительным) токеном ушло владельцу. Клик по этой
#  ссылке почтой не подтверждает ничего, а independent-таймер того же
#  первого запуска всё равно доходит до конца и выключает машину —
#  внешне выглядит ровно как прошлый баг, хотя причина теперь другая:
#  не последовательные входы, а конкурентные. Лечится обычным
#  файловым мьютексом: вся секция «проверить и, если нужно,
#  перевыпустить токен» теперь выполняется только одним запуском
#  хука за раз (mkdir атомарен — вторая попытка создать существующий
#  каталог гарантированно провалится), конкурирующие запуски просто
#  дожидаются своей очереди или тихо выходят, если не успели за
#  разумное время — и тогда уже идущий токен/таймер первого прохода
#  остаётся единственным источником истины, как и задумано.
# ============================================================
[ "${PAM_TYPE:-}" = "open_session" ] || exit 0

APP_DIR="${SKY_APP_DIR:-/opt/sky}"
CONTROL_DIR="$APP_DIR/control"
TOKEN_FILE="$CONTROL_DIR/ssh-confirm-token"
DONE_FILE="$CONTROL_DIR/ssh-login-confirmed"
SIGNAL_FILE="$CONTROL_DIR/shutdown-requested"
PAUSE_FILE="$CONTROL_DIR/pause"
LOCK_DIR="$CONTROL_DIR/.ssh-hook-lock"
DOMAIN="$(sed -n 's/^DOMAIN=//p' "$APP_DIR/.env" 2>/dev/null | tail -1)"
OWNER_EMAIL="deniskut43332@gmail.com"
CONFIRM_WINDOW_SEC=600
LOG="${SKY_HOOK_LOG:-/var/log/sky-ssh-hook.log}"

mkdir -p "$CONTROL_DIR"

# Правка (версия 2026-10-16): если включён шлюз ssh-gate.sh, этот вход УЖЕ подтверждён владельцем ДО открытия сессии
# (ссылка /ssh-verify + код аутентификатора). Второе письмо и 10-минутный таймер выключения тогда не нужны: ссылка из них
# (/ssh-confirm) — прежний способ «подтвердить после входа». Шлюз пишет отметку ssh-gate-approved; пропускаем только свежую
# (≤ 3 мин) и только для того же пользователя и адреса. Нет отметки (шлюз не стоит или отметки нет) — всё работает как раньше.
GATE_MARK="${SKY_GATE_MARK:-$CONTROL_DIR/ssh-gate-approved}"
if [ -r "$GATE_MARK" ]; then
  read -r G_TS G_USER G_RHOST < "$GATE_MARK" 2>/dev/null
  NOW_TS="$(date +%s)"
  if [ -n "${G_TS:-}" ] && [ "$G_TS" -le "$NOW_TS" ] 2>/dev/null && [ $((NOW_TS - G_TS)) -le 180 ] \
     && [ "$G_USER" = "${PAM_USER:-}" ] && [ "$G_RHOST" = "${PAM_RHOST:-}" ]; then
    echo "$(date -u +%FT%TZ) вход ${PAM_USER:-?}@${PAM_RHOST:-?} подтверждён шлюзом ssh-gate до открытия сессии — повторное подтверждение не нужно" >> "$LOG" 2>/dev/null
    exit 0
  fi
fi

# Мьютекс на решающую секцию ниже: mkdir — атомарная операция в POSIX,
# два одновременных процесса не могут оба её выполнить успешно. Лок
# снимается в любом случае выхода (EXIT trap), включая ранний `exit 0`
# из блока пропуска ниже.
lock_acquired=0
tries=0
while [ "$tries" -lt 20 ]; do
  if mkdir "$LOCK_DIR" 2>/dev/null; then
    lock_acquired=1
    break
  fi
  # Лок не моложе 5 секунд — не настоящая конкуренция, а чужой битый
  # процесс (убит/упал посреди критической секции, которая иначе
  # занимает миллисекунды). Снимаем и пробуем снова, а не ждём вечно.
  lock_age=$(( $(date +%s) - $(stat -c %Y "$LOCK_DIR" 2>/dev/null || echo 0) ))
  [ "$lock_age" -gt 5 ] && rmdir "$LOCK_DIR" 2>/dev/null
  tries=$((tries + 1))
  sleep 0.1
done

if [ "$lock_acquired" -ne 1 ]; then
  echo "$(date -u '+%Y-%m-%d %H:%M:%S') UTC: не удалось получить блокировку за 2с — выхожу без изменений (уже идущий цикл остаётся в силе)" >>"$LOG"
  exit 0
fi
trap 'rmdir "$LOCK_DIR" 2>/dev/null' EXIT

if [ -f "$TOKEN_FILE" ] && [ ! -f "$DONE_FILE" ]; then
  TOKEN_AGE=$(( $(date +%s) - $(stat -c %Y "$TOKEN_FILE" 2>/dev/null || echo 0) ))
  if [ "$TOKEN_AGE" -lt "$CONFIRM_WINDOW_SEC" ]; then
    echo "$(date -u '+%Y-%m-%d %H:%M:%S') UTC: вход во время уже идущего окна подтверждения — новый цикл не начинаю" >>"$LOG"
    exit 0
  fi
fi

rm -f "$DONE_FILE"
TOKEN="$(head -c32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
printf '%s' "$TOKEN" > "$TOKEN_FILE"
chmod 600 "$TOKEN_FILE"
LINK="https://${DOMAIN}/ssh-confirm?token=${TOKEN}"
WHEN="$(date -u '+%Y-%m-%d %H:%M:%S')"
WHO="${PAM_USER:-unknown}@${PAM_RHOST:-unknown}"

# Письмо-уведомление. Текст письма — в файле без переменных внутри
# JS-строки (шлётся через process.env), поэтому его можно положить на
# общий с контейнером том (control/) без какой-либо подстановки
# значений в сам JS — меньше экранирования, меньше риска сломать
# скрипт случайным символом в адресе/домене.
NOTIFY_JS="$CONTROL_DIR/.ssh-notify.mjs"
cat > "$NOTIFY_JS" <<'JS'
import('/app/server/notify.mjs').then(({ sendEmail }) => sendEmail(
  process.env.TO, 'Sky: вход по SSH — подтвердите, что это вы',
  'Зафиксирован успешный вход по SSH: ' + process.env.WHO + ', ' + process.env.WHEN + ' UTC.\n\n' +
  'Если это вы — подтвердите за 10 минут: ' + process.env.LINK + '\n\n' +
  'Если нет — ничего не делайте: через 10 минут сервер выключится сам.'
));
JS

setsid bash -c "
  cd '$APP_DIR' &&
  docker compose exec -T -e TO='$OWNER_EMAIL' -e LINK='$LINK' -e WHO='$WHO' -e WHEN='$WHEN' \
    api node /control/.ssh-notify.mjs
  rm -f '$NOTIFY_JS'
" </dev/null >>"$LOG" 2>&1 &
disown

setsid bash -c "
  sleep $CONFIRM_WINDOW_SEC
  [ -f '$DONE_FILE' ] && exit 0
  [ -f '$PAUSE_FILE' ] && exit 0
  mkdir -p '$CONTROL_DIR'
  printf '%s UTC\nВход по SSH (%s) не подтверждён за 10 минут\n' '$WHEN' '$WHO' > '$SIGNAL_FILE'
" </dev/null >>"$LOG" 2>&1 &
disown

exit 0
